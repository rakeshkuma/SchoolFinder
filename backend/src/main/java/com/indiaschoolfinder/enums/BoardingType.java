package com.indiaschoolfinder.enums;

/** How students live at the school, as stated by the cited source. */
public enum BoardingType {
    /** All (or nearly all) students live on campus during term. */
    FULL_BOARDING,
    /** Students board on weekdays and go home at weekends. */
    WEEKLY_BOARDING,
    /** Both day scholars and boarders are admitted. */
    DAY_CUM_BOARDING
}
