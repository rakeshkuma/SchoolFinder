package com.indiaschoolfinder.enums;

/** Entrance route into a residential school. Each system's eligibility rules are separate. */
public enum EntranceExam {
    /** Jawahar Navodaya Vidyalaya Selection Test. */
    JNVST,
    /** All India Sainik Schools Entrance Examination (NTA). */
    AISSEE,
    /** Rashtriya Military Schools Common Entrance Test. */
    RMS_CET,
    /** RIMC entrance examination, viva-voce and medical. */
    RIMC,
    /** Netarhat Awasiya Vidyalaya entrance examination. */
    NETARHAT,
    /** The school's own admission test or assessment. */
    SCHOOL_TEST
}
