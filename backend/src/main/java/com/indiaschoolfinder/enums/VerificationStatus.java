package com.indiaschoolfinder.enums;

/**
 * UNVERIFIED: collected from the cited source but not yet checked by an administrator.
 * VERIFIED: an administrator confirmed it against the cited source on last_verified_date.
 * OUTDATED: the source has since changed or the academic year has passed.
 * DISPUTED: a conflicting source or report exists.
 */
public enum VerificationStatus {
    UNVERIFIED,
    VERIFIED,
    OUTDATED,
    DISPUTED
}
