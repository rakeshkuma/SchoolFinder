// Builds a facts file (see school-facts.json) for Jawahar Navodaya Vidyalayas: classes from the national scheme rule
// (entry at Class VI, published by the Government of India) capped by each school's CBSE affiliation level, plus any
// map locations from match-osm.js.
//
// Usage: node build-jnv-facts.js <jnvs.json> <out.json> [locations.json]
//   jnvs.json: [{slug, level}] where level is the CBSE SARAS affiliation level ("Senior Secondary" or "Secondary");
//   schools with any other or no level are skipped.
const fs = require('fs');

const [inPath, outPath, locationsPath] = process.argv.slice(2);
if (!inPath || !outPath) {
  console.error('usage: node build-jnv-facts.js <jnvs.json> <out.json> [locations.json]');
  process.exit(2);
}
const read = (p) => JSON.parse(fs.readFileSync(p, 'utf8').replace(/^﻿/, ''));

const PIB_URL = 'https://www.pib.gov.in/PressReleasePage.aspx?PRID=2081690';
const PIB_QUOTE = "PIB, Government of India (6 Dec 2024): 'The NVs are fully residential, co-educational schools providing "
  + "good quality modern education from Class VI to XII' and 'students are admitted in NVs to class VI every year'.";
const LEVELS = {
  'Senior Secondary': { codes: ['VI', 'VII', 'VIII', 'IX', 'X', 'XI', 'XII'], note: 'CBSE SARAS lists this school as Senior Secondary (up to Class XII).' },
  Secondary: { codes: ['VI', 'VII', 'VIII', 'IX', 'X'], note: 'CBSE SARAS lists this school as Secondary (up to Class X), so classes XI and XII are not recorded.' },
};

const locations = new Map((locationsPath ? read(locationsPath).schools : []).map((s) => [s.slug, s.facts.location]));
const out = [];
let skipped = 0;
for (const s of read(inPath)) {
  const level = LEVELS[s.level];
  if (!level) {
    skipped++;
    continue;
  }
  const facts = { classes: { codes: level.codes, source: { url: PIB_URL, retrievedDate: '2026-10-25', note: `${PIB_QUOTE} ${level.note}` } } };
  if (locations.has(s.slug)) facts.location = locations.get(s.slug);
  out.push({ slug: s.slug, facts });
}
fs.writeFileSync(outPath, JSON.stringify({
  _comment: 'Generated by build-jnv-facts.js on 2026-10-25. Classes: the Government of India states Navodaya Vidyalayas teach Class VI to XII with entry at Class VI; each school is capped at its CBSE SARAS affiliation level. Locations: OpenStreetMap schools matched by match-osm.js (rules in that file; unmatched schools are left without a location).',
  schools: out,
}, null, 1));
console.log(`wrote ${out.length} schools (${[...out].filter((s) => s.facts.location).length} with a location), skipped ${skipped}`);
