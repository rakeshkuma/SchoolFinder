// Builds an admissions file for Jawahar Navodaya Vidyalayas from the official JNVST prospectus. Admission to Class VI
// in every JNV is through one national selection test, so the same cycle applies to each school.
//
// Usage: node build-jnv-admissions.js <jnvs.json> <out.json>
//   jnvs.json: [{slug}] (all JNV profiles)
//
// Source: NVS "Prospectus cum notification" for JNVST 2027, on the official admission portal
// (https://cbseitms.rcil.gov.in/nvs/), read 2026-10-25. Quoted there: the selection test "will be held on 28th November,
// 2026 for Summer bound and Winter bound JNVs in single phase"; "The last date to submit online application is 31st July,
// 2026"; candidates must be "bonafide residents of the district and studying in class V (2026-27) in recognized school",
// "Born between 01.05.2015 to 31.07.2017 (Both the dates inclusive)"; the result "is expected to be announced by end of
// March, 2027". The prospectus gives no opening date for applications, so none is recorded. Some third-party sites
// report a later deadline; that is not in the prospectus and is not used.
const fs = require('fs');

const [inPath, outPath] = process.argv.slice(2);
if (!inPath || !outPath) {
  console.error('usage: node build-jnv-admissions.js <jnvs.json> <out.json>');
  process.exit(2);
}
const PROSPECTUS = 'https://cbseitms.rcil.gov.in/nvs/assets/pdf/Final_Prospectus_2027.pdf';
const PORTAL = 'https://cbseitms.rcil.gov.in/nvs/';

const cycle = {
  classCode: 'VI',
  academicYear: '2027-28',
  category: 'GENERAL',
  applicationStartDate: null,
  applicationEndDate: '2026-07-31',
  ageEligibility: 'Born between 01.05.2015 and 31.07.2017 (both dates inclusive).',
  selectionCriteria: 'Admission to Class VI is through the Jawahar Navodaya Vidyalaya Selection Test (JNVST) 2027, held on '
    + '28 November 2026 in a single phase for summer- and winter-bound JNVs. The result is expected by the end of March 2027.',
  officialNotificationUrl: PROSPECTUS,
  applicationUrl: PORTAL,
  requirements: [
    { type: 'ELIGIBILITY', description: 'A bona fide resident of the district, studying in Class V in 2026-27 in a recognised school.', mandatory: true },
    { type: 'ELIGIBILITY', description: 'Born between 01.05.2015 and 31.07.2017 (both dates inclusive).', mandatory: true },
    { type: 'SELECTION_CRITERION', description: 'JNV Selection Test 2027 on 28 November 2026 (single phase).', mandatory: true },
  ],
  sourceUrl: PROSPECTUS,
  notes: 'From the NVS prospectus for JNVST 2027 (read 25 October 2026). The prospectus gives the last date to apply as '
    + '31 July 2026 and no opening date. Registration is free on the NVS admission portal. Seats, reservations and '
    + 'district-specific rules are in the prospectus.',
};

const jnvs = JSON.parse(fs.readFileSync(inPath, 'utf8').replace(/^﻿/, ''));
const schools = jnvs.map((s) => ({ slug: s.slug, admissions: [cycle] }));
fs.writeFileSync(outPath, JSON.stringify({
  _comment: 'Generated by build-jnv-admissions.js from the official JNVST 2027 prospectus (see that file for the quoted '
    + 'source). Entries are AdmissionRequest bodies for POST /api/v1/admin/schools/{id}/admissions, keyed by slug; '
    + 'loading them again updates the same cycle. Load with LocalAdmissionsImport or import-to-server.js.',
  schools,
}, null, 1));
console.log(`wrote ${schools.length} schools`);
