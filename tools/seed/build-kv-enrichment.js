// Turns kv-details.json (scraped from each KV's own kvs.ac.in site) into an enrichment file for apply-enrichment.js.
// Class lists are used only when they are contiguous and reach the level CBSE records (XII, or X for secondary).
// Usage: node build-kv-enrichment.js <seed.csv> <kv-details.json> <out.json>
const fs = require('fs');
const [csvPath, detailsPath, outPath] = process.argv.slice(2);
const ROMAN = ['I', 'II', 'III', 'IV', 'V', 'VI', 'VII', 'VIII', 'IX', 'X', 'XI', 'XII'];
// Official KVS statement repeated on every KV site ("All Kendriya Vidyalayas are co-educational, composite schools";
// "Common text-books and bilingual medium of instruction for all Kendriya Vidyalayas"), read on this page:
const KVS_POLICY = 'https://rkpuramsec2.kvs.ac.in/en/kvs-vision-and-mission/';

const details = JSON.parse(fs.readFileSync(detailsPath, 'utf8'));
const csvText = fs.readFileSync(csvPath, 'utf8');
const out = { _comment: 'Generated by build-kv-enrichment.js from each KV website (read 2026-10-24).' };
let classesUsed = 0;
for (const [name, d] of Object.entries(details)) {
  const line = csvText.split('\n').find((l) => l.startsWith(name + ',') || l.startsWith(`"${name}",`)) ?? '';
  const secondaryOnly = /at secondary level/.test(line);
  const e = { source: d.contactUrl ?? d.base + '/', gender_type: 'CO_ED', medium_of_instruction: 'Bilingual (Hindi and English)' };
  const notes = [`KVS states that all Kendriya Vidyalayas are co-educational and use a bilingual medium of instruction (${KVS_POLICY}).`];
  if (d.phone) e.phone = d.phone;
  if (d.email) e.email = d.email;
  const cls = d.classCodes ?? [];
  const idx = cls.map((c) => ROMAN.indexOf(c));
  const contiguous = idx.length > 0 && idx.every((v, i) => i === 0 || v === idx[i - 1] + 1);
  const top = secondaryOnly ? 'X' : 'XII';
  if (contiguous && cls[cls.length - 1] === top) {
    e.class_codes = cls.join(';');
    classesUsed++;
    notes.push(`Classes ${cls[0]}–${top} and ${d.studentsEnrolled} students enrolled as per the school's class-wise enrolment page`
      + `${d.enrolmentUpdated ? ` (updated ${d.enrolmentUpdated})` : ''}: ${d.enrolmentUrl}.`);
  }
  e.note = notes.join(' ');
  out[name] = e;
}
fs.writeFileSync(outPath, JSON.stringify(out, null, 2) + '\n');
const vals = Object.values(out).filter((v) => typeof v === 'object');
console.log(`KVs ${vals.length}, with phone ${vals.filter((v) => v.phone).length}, email ${vals.filter((v) => v.email).length}, classes ${classesUsed}`);
