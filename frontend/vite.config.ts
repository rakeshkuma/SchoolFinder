/// <reference types="vitest" />
import { defineConfig, type Plugin } from 'vite';
import react from '@vitejs/plugin-react';

/**
 * index.html carries nginx server-side-include directives for page-specific <head> tags (see nginx.conf). The dev
 * server has no SSI, so it serves the fallback block in their place; production builds keep the directives.
 */
function ssiFallbackInDev(): Plugin {
  return {
    name: 'ssi-fallback-in-dev',
    apply: 'serve',
    transformIndexHtml: (html) => html
      .replace(/<!--# block name="seo_default" -->([\s\S]*?)<!--# endblock -->/, '$1')
      .replace(/<!--# include [^>]*-->/g, ''),
  };
}

// In development the API is proxied so the browser talks to one origin (no CORS needed locally).
export default defineConfig({
  plugins: [react(), ssiFallbackInDev()],
  server: {
    port: 5173,
    proxy: {
      '/api': {
        target: process.env.VITE_DEV_API_PROXY ?? 'http://localhost:8080',
        changeOrigin: true,
      },
      // robots.txt and sitemaps are generated by the backend.
      '^/(robots\\.txt|sitemap\\.xml|sitemaps/.*)$': {
        target: process.env.VITE_DEV_API_PROXY ?? 'http://localhost:8080',
        changeOrigin: true,
      },
    },
  },
  build: {
    sourcemap: false,
    rollupOptions: {
      output: {
        // Separate long-lived vendor chunks so app changes don't invalidate cached libraries.
        manualChunks: {
          react: ['react', 'react-dom', 'react-router-dom'],
          charts: ['recharts'],
          maps: ['leaflet', 'react-leaflet'],
        },
      },
    },
  },
  test: {
    environment: 'jsdom',
    include: ['src/**/*.test.ts', 'src/**/*.test.tsx'],
  },
});
