/// <reference types="vitest" />
import { defineConfig, type Plugin } from 'vite';
import react from '@vitejs/plugin-react';

/**
 * index.html carries nginx server-side-include directives for page-specific <head> tags (see nginx.conf). The dev
 * server has no SSI, so it serves the fallback block in their place; production builds keep the directives.
 */
function ssiFallbackInDev(): Plugin {
  return {
    name: 'ssi-fallback-in-dev',
    apply: 'serve',
    transformIndexHtml: (html) => html
      .replace(/<!--# block name="seo_default" -->([\s\S]*?)<!--# endblock -->/, '$1')
      .replace(/<!--# include [^>]*-->/g, ''),
  };
}

const apiTarget = process.env.VITE_DEV_API_PROXY ?? 'http://localhost:8080';

/**
 * Vite answers a failed proxy connection with a bare 500, which reads like a server bug. When the backend is not
 * running (or still starting), answer 503 with the API's error shape instead, so the UI says the service is unavailable.
 */
function backendUnavailable(proxy: { on(event: 'error', fn: (err: Error, req: unknown, res: unknown) => void): void }) {
  proxy.on('error', (err, _req, res) => {
    const out = res as import('node:http').ServerResponse;
    if (typeof out.writeHead !== 'function' || out.headersSent || out.writableEnded) return;
    console.warn(`[api proxy] backend at ${apiTarget} unreachable: ${(err as NodeJS.ErrnoException).code ?? err.message}`);
    out.writeHead(503, { 'Content-Type': 'application/json', 'Retry-After': '5' }).end(JSON.stringify({
      status: 503, error: 'Service Unavailable',
      message: 'The service is temporarily unavailable. Please try again shortly.', fieldErrors: [],
    }));
  });
}

// In development the API is proxied so the browser talks to one origin (no CORS needed locally).
export default defineConfig({
  plugins: [react(), ssiFallbackInDev()],
  server: {
    port: 5173,
    proxy: {
      '/api': {
        target: apiTarget,
        changeOrigin: true,
        configure: backendUnavailable,
      },
      // robots.txt and sitemaps are generated by the backend.
      '^/(robots\\.txt|sitemap\\.xml|sitemaps/.*)$': {
        target: apiTarget,
        changeOrigin: true,
      },
    },
  },
  build: {
    sourcemap: false,
    rollupOptions: {
      output: {
        // Separate long-lived vendor chunks so app changes don't invalidate cached libraries.
        manualChunks: {
          react: ['react', 'react-dom', 'react-router-dom'],
          charts: ['recharts'],
          maps: ['leaflet', 'react-leaflet'],
        },
      },
    },
  },
  test: {
    environment: 'jsdom',
    include: ['src/**/*.test.ts', 'src/**/*.test.tsx'],
  },
});
